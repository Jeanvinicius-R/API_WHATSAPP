export const reducedMotion = () => window.matchMedia('(prefers-reduced-motion: reduce)').matches;

/** Chamada à API. Sempre devolve { status, data } — nunca lança por status HTTP. */
export async function api(path, { method = 'GET', body } = {}) {
  try {
    const res = await fetch(path, {
      method,
      headers: body ? { 'Content-Type': 'application/json' } : undefined,
      body: body ? JSON.stringify(body) : undefined,
      cache: 'no-store',
    });
    const data = await res.json().catch(() => ({}));
    return { status: res.status, data };
  } catch {
    return { status: 0, data: { erro: { codigo: 'SEM_CONEXAO', mensagem: 'Sem conexão com o servidor. Verifique se o programa está rodando.' } } };
  }
}

export function fmtMoney(value, currency) {
  const locale = { BRL: 'pt-BR', USD: 'en-US', CAD: 'en-CA', EUR: 'de-DE' }[currency] || 'pt-BR';
  const decimals = value % 1 !== 0 && value < 1000 ? 2 : 0;
  return new Intl.NumberFormat(locale, {
    style: 'currency', currency, minimumFractionDigits: decimals, maximumFractionDigits: decimals,
  }).format(value);
}

/** Anima um número de 0 até `to` (respeita movimento reduzido). */
export function countUp(el, to, { duration = 1400, suffix = '' } = {}) {
  if (reducedMotion()) { el.textContent = `${to}${suffix}`; return; }
  const t0 = performance.now();
  const tick = (t) => {
    const p = Math.min(1, (t - t0) / duration);
    const eased = 1 - (1 - p) ** 3;
    el.textContent = `${Math.round(to * eased)}${suffix}`;
    if (p < 1) requestAnimationFrame(tick);
  };
  requestAnimationFrame(tick);
}
